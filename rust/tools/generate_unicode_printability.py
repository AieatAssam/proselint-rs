#!/usr/bin/env python3
"""Generate Rust's static Python 3.12.3 str.isprintable() false table."""
import argparse
import pathlib
import sys
import unicodedata

OUTPUT = pathlib.Path(__file__).resolve().parents[1] / "src" / "unicode_printability.rs"
HEADER = '''// Generated by rust/tools/generate_unicode_printability.py using CPython 3.12.3 / UCD 15.0.0.
// Derived Unicode data; see rust/data/unicode/Unicode-3.0.txt for the full notice.
const NONPRINTABLE: &[(u32, u32)] = &[\n'''


def generate() -> str:
    if sys.version_info[:3] != (3, 12, 3) or unicodedata.unidata_version != "15.0.0":
        raise SystemExit(
            f"requires Python 3.12.3 / UCD 15.0.0; got {sys.version.split()[0]} / {unicodedata.unidata_version}"
        )
    intervals = []
    start = previous = None
    for codepoint in range(0x110000):
        if chr(codepoint).isprintable():
            if start is not None:
                intervals.append((start, previous))
                start = previous = None
        elif start is None:
            start = previous = codepoint
        else:
            previous = codepoint
    if start is not None:
        intervals.append((start, previous))
    rows = "".join(f"    (0x{first:04X}, 0x{last:04X}),\n" for first, last in intervals)
    return HEADER + rows + "];\n\npub(crate) fn is_printable(character: char) -> bool {\n    let codepoint = character as u32;\n    let index = NONPRINTABLE.partition_point(|&(_, end)| end < codepoint);\n    NONPRINTABLE\n        .get(index)\n        .is_none_or(|&(start, _)| codepoint < start)\n}\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if the generated Rust table is stale")
    args = parser.parse_args()
    output = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != output:
            print(f"{OUTPUT} is stale; regenerate with {sys.executable} {__file__}", file=sys.stderr)
            return 1
        print(f"verified {OUTPUT}")
    else:
        OUTPUT.write_text(output, encoding="utf-8", newline="\n")
        print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
